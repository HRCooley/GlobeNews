    fun search(query: String): Location? {
        if (query.isBlank()) return null
        val lower = query.lowercase().trim()

        // Exact match first
        knownLocations.firstOrNull { it.name.lowercase() == lower }?.let { return it }

        // Contains match (query in location name)
        knownLocations.firstOrNull { it.name.lowercase().contains(lower) }?.let { return it }

        // Reverse contains (location name in query, for things like "northern virginia")
        knownLocations.firstOrNull { lower.contains(it.name.lowercase()) }?.let { return it }

        // Fuzzy: match first word
        val firstWord = lower.split(" ").first()
        if (firstWord.length >= 3) {
            knownLocations.firstOrNull { it.name.lowercase().startsWith(firstWord) }?.let { return it }
        }

        return null
    }
